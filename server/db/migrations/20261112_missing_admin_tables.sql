-- 20261112_missing_admin_tables.sql
--
-- Creates the tables the admin server references but that were never created
-- in the database.
--
-- WHY THIS FILE EXISTS
--   Seven tables are referenced by the server code but do not exist:
--     roles, user_roles, app_settings, check_ins, entity_flags, fee_configs,
--     user_notes
--   Every endpoint backed by one of them answers 500, so the corresponding
--   admin pages are broken (Settings, Roles, Check-ins, Flags, Fees, Notes)
--   and the team role cannot be resolved from the role table.
--
--   The role is read from the first source that has it: the `user_roles`
--   table, then `auth.users.app_metadata.gawa_role`, then
--   `users_table.role`. This migration creates the role table, so it takes
--   over from then on. Nothing else has to change.
--
-- WHAT THIS FILE DOES NOT DO
--   It does not alter any existing table. In particular it does not touch
--   `users_table`:
--
--     * No CHECK constraint is added to `users_table.role`. The mobile app
--       owns the consumer roles and writes them in mixed case
--       ('Client' and 'client', 'Talent' and 'talent', 'Equipment Owner' and
--       'equipment_owner'), and new ones will be added over time. A
--       constraint that has to enumerate them all would break the mobile app
--       the first time it adds a value. The server already restricts the
--       roles it accepts to 'admin' and 'customer_support', in
--       server/utilities/permissions.js, which is where that rule belongs.
--
--     * No row level security policy is added to `users_table`. The mobile
--       app reads that table directly with the anon key, so changing its
--       policies can change mobile behaviour. There IS a live exposure there
--       — see the optional section at the end of this file — but it needs a
--       decision about the mobile app first, so it is not applied here.
--
-- HOW TO APPLY
--   Paste into the Supabase SQL Editor and run it once. It is idempotent.
--
--   Afterwards, run:
--     node scripts/seed-team-roles.js
--   to copy the existing role assignments into the new table. This is
--   optional: until the role table exists the server reads the role from
--   `users_table.role` anyway.
--
-- VERIFY
--   select table_name from information_schema.tables
--     where table_schema = 'public'
--       and table_name in ('roles','user_roles','app_settings','check_ins',
--                          'entity_flags','fee_configs','user_notes');
--   -- must return 7 rows

-- ---------------------------------------------------------------------------
-- 1. Role tables
-- ---------------------------------------------------------------------------

create table if not exists public.roles (
  role_id   bigint generated by default as identity primary key,
  role_name text not null,
  constraint roles_role_name_key unique (role_name)
);

comment on table public.roles is 'Named team roles. Admin server only.';

create table if not exists public.user_roles (
  user_role_id bigint generated by default as identity primary key,
  user_id      uuid not null references public.users_table(id) on delete cascade,
  role_id      bigint not null references public.roles(role_id) on delete cascade,
  constraint user_roles_user_role_key unique (user_id, role_id)
);

create index if not exists user_roles_user_id_idx on public.user_roles (user_id);

comment on table public.user_roles is 'Maps an account to a team role. Admin server only.';

insert into public.roles (role_name) values ('admin'), ('customer_support')
on conflict (role_name) do nothing;

-- Backfill from the profile column. Only rows that already claim a known team
-- role are copied, so this cannot be used to grant a role to a consumer.
insert into public.user_roles (user_id, role_id)
select u.id, r.role_id
from public.users_table u
join public.roles r on r.role_name = u.role
on conflict (user_id, role_id) do nothing;

-- ---------------------------------------------------------------------------
-- 2. Admin feature tables
-- ---------------------------------------------------------------------------

-- Runtime settings (key/value), e.g. the moderation windows.
create table if not exists public.app_settings (
  key        text primary key,
  value      text,
  updated_by uuid references public.users_table(id) on delete set null,
  updated_at timestamptz not null default now()
);

comment on table public.app_settings is 'Runtime configuration. Managed by administrators.';

-- A worker checking in on a job.
create table if not exists public.check_ins (
  check_in_id   uuid primary key default gen_random_uuid(),
  job_match_id  uuid not null references public.job_matches(job_match_id) on delete cascade,
  client_id     uuid references public.users_table(id) on delete set null,
  user_id       uuid references public.users_table(id) on delete set null,
  location_lat  double precision,
  location_lng  double precision,
  checked_in_at timestamptz not null default now(),
  created_at    timestamptz not null default now()
);

create index if not exists check_ins_job_match_id_idx on public.check_ins (job_match_id);

comment on table public.check_ins is 'Job check-ins. Written by the mobile app.';

-- A moderation flag raised against any entity.
create table if not exists public.entity_flags (
  flag_id     uuid primary key default gen_random_uuid(),
  entity_type text not null,
  entity_id   uuid not null,
  flagged_by  uuid references public.users_table(id) on delete set null,
  reason      text,
  created_at  timestamptz not null default now()
);

create index if not exists entity_flags_entity_idx on public.entity_flags (entity_type, entity_id);

comment on table public.entity_flags is 'Moderation flags. Admin server only.';

-- Platform fee configuration. Exactly one row may be active at a time.
create table if not exists public.fee_configs (
  id                   uuid primary key default gen_random_uuid(),
  name                 text not null,
  proposal_gp_cost     numeric not null default 50,
  platform_fee_percent numeric not null default 2.5,
  gp_conversion_rate   numeric not null default 1.0,
  listing_fee          numeric not null default 0,
  is_active            boolean not null default false,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  constraint fee_configs_percent_range check (platform_fee_percent >= 0 and platform_fee_percent <= 100),
  constraint fee_configs_conversion_positive check (gp_conversion_rate > 0)
);

create unique index if not exists fee_configs_one_active_idx
  on public.fee_configs (is_active) where is_active;

comment on table public.fee_configs is 'Platform fee configuration. Read by the mobile app.';

-- Notes an administrator leaves on a user.
create table if not exists public.user_notes (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references public.users_table(id) on delete cascade,
  content    text not null,
  author_id  uuid references public.users_table(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists user_notes_user_id_idx on public.user_notes (user_id);

comment on table public.user_notes is 'Administrator notes on a user. Admin server only.';

-- ---------------------------------------------------------------------------
-- 3. Row level security on the new tables
-- ---------------------------------------------------------------------------
-- Applied only to the tables the mobile app has no reason to touch. Enabling
-- RLS with no policy denies every read to anon and authenticated clients,
-- while the admin server keeps working through its service-role key.
--
-- `check_ins` and `fee_configs` are deliberately left open: the mobile app
-- writes check-ins and reads the fee configuration, so restricting them here
-- could break it.

alter table public.roles enable row level security;
alter table public.user_roles enable row level security;
alter table public.app_settings enable row level security;
alter table public.entity_flags enable row level security;
alter table public.user_notes enable row level security;

-- ---------------------------------------------------------------------------
-- 4. Optional: hardening `users_table` — REVIEW BEFORE RUNNING
-- ---------------------------------------------------------------------------
-- NOT APPLIED BY THIS SCRIPT. Read the notes before running it.
--
-- Live exposure: with row level security off on `users_table`, the anon key
-- that ships in the mobile app can read the whole table. This was verified
-- against the live database:
--
--   curl "$SUPABASE_URL/rest/v1/users_table?select=id,email,phone,role" \
--        -H "apikey: $SUPABASE_ANON_KEY"
--
-- returns every user's id, email, phone, address, date of birth and role,
-- with no session at all. The same anon key CANNOT change the role: a
-- signed-in consumer updating its own `role` affects zero rows, so the
-- privilege escalation path is closed. It is the read that is open.
--
-- The policies below close the read. They also make the existing
-- protection of the role column explicit, by comparing the written value
-- against the stored one.
--
-- Before running this, check what the mobile app reads from `users_table`
-- and with which key. If the mobile app lists other users (a directory, a
-- ratings list, a leaderboard) it needs an explicit read policy instead of
-- the narrow one below.
--
-- alter table public.users_table enable row level security;
--
-- drop policy if exists "users read own profile" on public.users_table;
-- create policy "users read own profile"
--   on public.users_table for select to authenticated
--   using (auth.uid() = id);
--
-- drop policy if exists "users update own profile" on public.users_table;
-- create policy "users update own profile"
--   on public.users_table for update to authenticated
--   using (auth.uid() = id)
--   with check (
--     auth.uid() = id
--     and role = (select u.role from public.users_table u where u.id = auth.uid())
--   );
--
-- Do NOT add a CHECK constraint to `users_table.role`: the mobile app owns
-- the consumer role values and adds new ones over time.
